#!/usr/bin/env python3
"""Build five small, precomposed garden stages and their firmware JPEG data."""
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
folder=root/'assets/study-garden'
base=Image.open(folder/'background-source.png').convert('RGB').resize((320,240),Image.Resampling.LANCZOS).convert('RGBA')
sprite=Image.open(folder/'bamboo-source.png').convert('RGBA')
a=sprite.getchannel('A').point(lambda v: 0 if v<70 else min(255,(v-70)*255//150))
sprite.putalpha(a)
sprite=sprite.crop(a.getbbox())
(folder/'stages').mkdir(exist_ok=True)
# Alternate sides, keeping the panda and top labels clear.
positions=[(28,80,48,100),(244,87,46,94),(56,111,35,70),(218,111,35,70)]
arrays=[]
for n in range(5):
    im=base.copy()
    for x,y,w,h in positions[:n]:
        plant=sprite.resize((w,h),Image.Resampling.LANCZOS)
        im.alpha_composite(plant,(x,y))
    path=folder/'stages'/f'garden-{n}.jpg'
    im.convert('RGB').save(path,'JPEG',quality=85,subsampling=0,progressive=False)
    data=path.read_bytes()
    arrays.append('static const uint8_t GARDEN_%d[] = {\n%s\n};\n'%(n, '\n'.join('  '+','.join('0x%02x'%b for b in data[i:i+16])+',' for i in range(0,len(data),16))))
header='#pragma once\n#include <stdint.h>\n// Generated by tools/prepare_garden_art.py.\n'+''.join(arrays)
(root/'firmware/BhoomiClock/garden_jpg.h').write_text(header)
