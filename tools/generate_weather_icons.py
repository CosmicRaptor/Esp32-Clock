"""Generate compact, original 16px monochrome weather glyphs. No font/image dependencies."""
from pathlib import Path
import math

codes = [0x2600, 0x263e, 0x26c5, 0x2601, 0x224b, 0x3df, 0x2744, 0x2602]

def pixel(kind, x, y):
    sun = (x-7.5)**2+(y-7.5)**2 <= 11 or any(abs((x-7.5)*math.sin(a)-(y-7.5)*math.cos(a)) < .7 and 5 < (x-7.5)*math.cos(a)+(y-7.5)*math.sin(a) < 7.8 for a in [i*math.pi/4 for i in range(8)])
    moon = (x-7.5)**2+(y-7.5)**2 <= 48 and (x-11)**2+(y-4.5)**2 > 40
    cloud = ((x-5)**2+(y-8)**2 <= 12 or (x-9)**2+(y-6)**2 <= 17 or (x-12)**2+(y-9)**2 <= 10 or 3 <= x <= 12 and 8 <= y <= 11)
    if kind == 0: return sun
    if kind == 1: return moon
    if kind == 2: return cloud or sun and x < 8 and y < 8
    if kind == 3: return cloud
    if kind == 4: return 2 <= x <= 13 and any(abs(y-row-math.sin(x*.8)) < .8 for row in (4,8,12))
    if kind == 5: return (6 <= y <= 8 and 4 <= x <= 11) or (2 <= y < 6 and abs(x-(10-y*.7))<1.3) or (8 < y <= 14 and abs(x-(14-y*.65))<1.1)
    if kind == 6: return 2 <= x <= 13 and 2 <= y <= 13 and (abs(x-7.5)<.8 or abs(y-7.5)<.8 or abs(x-y)<.8 or abs(x+y-15)<.8)
    return cloud and y < 10 or any(abs(x-(a-(y-11)*.35)) < .7 and 11 <= y <= 14 for a in (4,8,12))

rows=[]
for i in range(8):
    bits=[pixel(i,x,y) for y in range(16) for x in range(16)]
    rows.append(','.join(str(sum(int(bits[j+k]) << (7-k) for k in range(8))) for j in range(0,256,8)))
code='''// Generated by tools/generate_weather_icons.py. Original compact weather symbols.
#include "weather_icons.h"
namespace {
const uint8_t pixels[8][32] = {\n'''+',\n'.join('{'+r+'}' for r in rows)+'''};
const uint32_t codes[] = {'''+','.join(hex(c) for c in codes)+'''};
bool describe(const lv_font_t *, lv_font_glyph_dsc_t *d, uint32_t letter, uint32_t) {
  for (int i=0; i<8; ++i) if (codes[i] == letter) {
    d->adv_w=18; d->box_w=16; d->box_h=16; d->ofs_x=0; d->ofs_y=0;
    d->format=LV_FONT_GLYPH_FORMAT_A1; d->gid.index=i; d->is_placeholder=false; d->entry=nullptr; return true;
  }
  return false;
}
const void *bitmap(lv_font_glyph_dsc_t *d, lv_draw_buf_t *buf) {
  if (!buf || !buf->data || d->gid.index >= 8) return nullptr;
  // LVGL 9 draws every mask as A8 and expects a draw-buffer object, not raw packed bits.
  const uint8_t *src = pixels[d->gid.index];
  uint32_t stride = lv_draw_buf_width_to_stride(16, LV_COLOR_FORMAT_A8);
  for (int y=0; y<16; ++y) {
    for (int x=0; x<16; ++x) {
      int bit = y*16+x;
      buf->data[y*stride+x] = (src[bit/8] & (0x80 >> (bit%8))) ? 255 : 0;
    }
    for (uint32_t x=16; x<stride; ++x) buf->data[y*stride+x] = 0;
  }
  return buf;
}
}
lv_font_t weather_icons = [] { lv_font_t f = {}; f.get_glyph_dsc=describe; f.get_glyph_bitmap=bitmap;
  f.line_height=20; f.base_line=3; return f; }();
'''
Path('weather_icons.cpp').write_text(code)
